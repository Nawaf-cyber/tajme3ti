/**
 * ============ متاجر تكذب في بياناتها المُهيكلة ============
 *
 * الأصل أن يُصدَّق `schema.org/availability`: هو بيانُ المتجر عن نفسه،
 * وهو ما يقرأه جوجل. لكنّ متجراً واحداً عندنا لا يُحدّثه.
 *
 * ⚠️ قِيس يوم 2026-09-16 على «Thermalright Burst Assassin 120 EVO DARK»
 * في إنفيني آرك: الصفحة تكتب «Availability: Out of Stock» وزرُّ الشراء
 * معطَّل، وفي نفس الصفحة `"availability": "https://schema.org/InStock"`.
 *
 * والضرر مضاعف، لأنّ بياناتهم تُقرأ من مسارين:
 *   • «اكتشف الجديد» عبر `readProductPage` — فتُعرض قطعةٌ نافدة كأنها
 *     جاهزة للإضافة إلى الكتالوج.
 *   • دورةُ الأسعار عبر `scrapeGeneric` (المتجر على `scrapeMode: 'auto'`)
 *     — فيبقى العرض «متوفّراً» عند الزائر بسعرٍ لا يستطيع شراءه، ويظلّ
 *     ينافس على «أرخص سعر» فيسحب إليه كلّ من يقارن.
 *
 * ⚠️ ولا نبحث عن العبارة في الصفحة كلّها: صفحاتهم تعرض أسفلها منتجاتٍ
 * مشابهة قد يكون بعضها نافداً، فالبحثُ الحرّ يُدين الصفحة بمخزون جارتها.
 * المصدر الصادق هو **زرّ الشراء** نفسه.
 *
 * ⚠️ وهذا الملفّ نسخةٌ واحدة يستوردها المساران معاً. ولا يُنسخ المنطق في
 * أيٍّ منهما: خطأ كازاسوق عاش مرّةً في نسختين وأفسد الأسعار من البداية.
 */

/** الصفحات المعطَّلة الشراء في إنفيني آرك — الزرّ وحده لا الصفحة كلّها */
const INFINIARC_SOLD_OUT = /btn-buy-primary[^>]*\bdisabled\b[^>]*>\s*Out of Stock/i;

/**
 * @param url    رابط صفحة المنتج — منه يُعرف المتجر
 * @param html   نصّ الصفحة كما وصل
 * @param inStock ما قالته البيانات المُهيكلة
 * @returns الحكم بعد التصحيح — ويُعاد كما هو لكلّ متجرٍ آخر
 */
export function correctStock(url: string, html: string, inStock: boolean): boolean {
  let host = '';
  try { host = new URL(url).hostname; } catch { return inStock; }
  if (/(^|\.)infiniarc\.com$/i.test(host) && INFINIARC_SOLD_OUT.test(html)) return false;
  return inStock;
}
