/** الدينار البحريني بالريال — **كما يحوّله كازاسوق نفسه** فيرى الزائر عندنا الرقم الذي يراه عندهم.
 *  ⚠️ كان ١٠ («والمتجر نفسه يستعمل هذا التحويل») حتى غيّروا موقعهم (~2026-10-25): صار يعرض
 *  275 دينار = «SR 2744.59»، و335 = 3343.41، و147 = 1467.11، و2400 = 23952.81، و2700 = 26946.92.
 *  والأسعار الكبيرة تحسم الخانة السادسة: 9.98033 أخطأ الأخيرتين بقرشين، و9.980339 يعيد الخمس
 *  حرفياً (قِيس 2026-10-28 على ٢٥٢ عرضاً). وبالعشرة كان سعرنا أعلى من سعرهم بـ٠٫٢٪. وإن غيّروه يُقاس كذلك. */
export const BHD_TO_SAR = 9.980339;

/** هل نصّ السعر معلَنٌ بالدينار البحريني؟ */
export const isBhdText = (text: string): boolean =>
  /BHD/i.test(text) || text.includes('د.ب');

/** يحوّل رقماً بحرينيّاً إلى ريال — والصفر وما دونه يبقى كما هو */
export const bhdToSar = (n: number): number => (n > 0 ? n * BHD_TO_SAR : n);
