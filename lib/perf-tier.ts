/* ============ مستوى أداء المعالج (performanceTier) من القياس ============
 *
 * ⚠️ كان المستوى يُكتب يدوياً لكلّ معالج، فتناقض مع القياس: Ryzen 5 9600 = 4 ونظيره الأسرع
 * 9600X = 3، وCore Ultra 9 285K = 5 وأداؤه في الألعاب (71.8) أقلّ من 9600X (72.6). والباني
 * يقارن مستوى المعالج بمستوى الكرت (الفرق ≥٢ = «المعالج يحدّ من الكرت»)، ومنه بطاقات الفريمات
 * واقتراحات الترقية وخطط المساعد — فكان الحكم مقلوباً (بلاغ نوّاف 2026-10-21).
 *
 * فالمستوى من أداء الألعاب المقيس (lib/cpu-perf · Tom's Hardware، ٪ من أسرع معالج)، والحدود
 * عند الفجوات الطبيعيّة في الجدول: ٨٣٫٩ ← ٧٨٫٢ (فجوة ٥٫٧)، و٦٥٫٨ ← ٦٢٫٥ (٣٫٣).
 * وما لا قياس له يأخذ مستوى نظيره المقيس (cpuStem): F/KF/KS والنسخة بلا X نفسُ الشريحة.
 * وما لا قياس له ولا نظير يبقى بمستواه المكتوب — لا تقدير.
 */

export const cpuTierFromGaming = (gaming: number): number =>
  gaming >= 80 ? 5 : gaming >= 74 ? 4 : gaming >= 64 ? 3 : gaming >= 50 ? 2 : 1;

/** الطراز بلا لاحقة النسخة: «Core i5-14600KF» و«Core i5-14600K» ← «Core i5-14600»؛ و«X3D» لا يُمسّ */
export const cpuStem = (name: string): string =>
  name.replace(/\s+/g, ' ').trim().replace(/(KS|KF|K|F|X)$/i, '');

/** مستوى «العمل» (مونتاج وتصميم) من تعدّد الأنوية المقيس (lib/cpu-perf · multi، ٪ من الأسرع).
 *  الحدود عند الفجوات: ٧٧٫٩ ← ٧٥٫٩، و٦٤٫٥ ← ٥٤٫٨ (أكبرها: ٩٫٧)، و٤٥ ← ٤٢٫٨.
 *  يقرؤه مخطّط المساعد (lib/intent-plans) لاستخدام «مونتاج وتصميم» وحده — والمستوى المخزَّن
 *  في القاعدة يبقى مستوى الألعاب الذي يحكم به الباني على الاختناق. */
export const cpuTierFromMulti = (multi: number): number =>
  multi >= 77 ? 5 : multi >= 60 ? 4 : multi >= 45 ? 3 : multi >= 30 ? 2 : 1;
