/* ============ رابط الدخول محتفظاً بمكان المستخدم ============
 *
 * كان كل زرّ «سجّل الدخول» يشير إلى `/login` المجرّد، والصفحة تُعيد الجميع
 * إلى الرئيسية — فمن دُعي للتسجيل وهو في منتصف عمل (يقترح قطعة، أو يضع
 * قطعةً في تجميعة) يعود فلا يجد ما كان فيه.
 *
 * ⚠️ ويُحسب عند النقر لا عند الرسم: حسابه في الرسم يحتاج `useSearchParams`،
 * وهو يوجب حدَّ Suspense في كل صفحةٍ تعرض الزرّ — ثلاث صفحاتٍ ثمناً لسطر.
 * وحسابه لحظةَ النقر يقرأ العنوان الحقيقي بمعاملاته (`/builder?cpu=…` تحمل
 * التجميعة كلها في معاملاتها، وفقدُها يفقدها).
 *
 * ويبقى `href="/login"` مكتوباً على الوسم كما هو: من يفتح بزرٍّ أوسط أو
 * بلا جافاسكربت يصل إلى صفحة الدخول، وإن عاد إلى الرئيسية.
 */

export const loginHrefNow = (): string => {
  if (typeof window === 'undefined') return '/login';
  const back = window.location.pathname + window.location.search;
  return back === '/' ? '/login' : `/login?callbackUrl=${encodeURIComponent(back)}`;
};

/** يُركَّب على `onClick` لأي رابط دخول: يمنع التنقّل ثم يذهب حاملاً الوجهة. */
export const goToLogin = (e: { preventDefault: () => void }): void => {
  e.preventDefault();
  window.location.href = loginHrefNow();
};

/* ============ حارس وجهة العودة ============
 *
 * `callbackUrl` يصل من عنوان الصفحة، فيكتبه من شاء بما شاء. ورابطٌ
 * خارجيّ فيه يصير **إعادة توجيهٍ مفتوحة**: يُرسَل المستخدم بعد دخولٍ
 * حقيقيٍّ عندنا إلى موقعٍ ينتحل مظهرنا، وقد رأى بعينه أنه جاء من عندنا.
 *
 * فلا يُقبل إلا مسارٌ داخليّ:
 *   • يبدأ بشرطةٍ واحدة `/`
 *   • ولا يبدأ بـ`//` — تلك عنوانٌ مطلقٌ بلا بروتوكول (`//evil.com`)
 *   • ولا بـ`/\` — تتساهل بعض المتصفّحات فتقرأها كالسابقة
 * وما عدا ذلك يُردّ إلى الرئيسية بصمت.
 */
export const safeCallback = (raw: string | null): string =>
  raw && raw.startsWith('/') && !raw.startsWith('//') && !raw.startsWith('/\\') ? raw : '/';
