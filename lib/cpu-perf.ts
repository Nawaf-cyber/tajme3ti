export type CpuPerf = { chip: string; gaming: number | null; single: number | null; multi: number | null };

const norm = (s: string) => s.toUpperCase().replace(/\s+/g, ' ').trim();
const BY = new Map(ROWS.map((r) => [norm(r[0]), r]));

/**
 * أداء المعالج لاسم القطعة — null لما ليس في الجداول.
 *
 * ⚠️ قواعد المطابقة، ولا غيرها:
 *   • F وKF = نفس الشريحة بلا رسوميات مدمجة — الأداء نفسه (14600KF ← 14600K).
 *   • «250K» و«270K» عندنا = «250K Plus» و«270K Plus» في الجدول (اسم إنتل للتحديث).
 *   • ولا مطابقة بين X وغير X، ولا K وغير K: 7600 و265F و14700 أقلّ قدرةً
 *     من نظائرها — لا يُعطَين رقماً ليس لهنّ.
 */
export function cpuPerf(name: string): CpuPerf | null {
  const n = norm(name);
  const tries = [
    n,
    n.replace(/(\d)KF$/, '$1K'),          // 14600KF → 14600K
    n.replace(/(\d)F$/, '$1'),            // 14400F → 14400، 225F → 225
    /\d$/.test(n) ? `${n}F` : n,          // 14100 → 14100F: والعكس — الجدول قد لا يذكر إلّا نسخة F
    `${n} PLUS`,                          // 250K → 250K Plus
  ];
  for (const t of tries) {
    const r = BY.get(t);
    if (r) return { chip: r[0], gaming: r[1], single: r[2], multi: r[3] };
  }
  return null;
}

